
import json
import streamlit as st
from analysis_engine import analyze_report
from meta_explainer import explain_findings

st.set_page_config(
    page_title="Health App Privacy Explainer",
    page_icon="🛡️",
    layout="wide",
)

st.title("🛡️ Health App Privacy Explainer")
st.write(
    "Explore Android health-app permissions, third-party SDK "
    "indicators, and potential privacy concerns."
)

st.info(
    "This tool analyzes static indicators. A permission or SDK "
    "does not prove that an app collects or shares personal data."
)

uploaded_file = st.file_uploader(
    "Upload a MobSF JSON report",
    type=["json"],
)

if uploaded_file is not None:
    try:
        report = json.load(uploaded_file)

        if not isinstance(report, dict):
            st.error("The JSON report must contain an object.")
            st.stop()

        findings = analyze_report(report)
        summary = findings["summary"]

        st.subheader(findings["app_name"])
        st.caption(f"Package: {findings['package_name']}")

        col1, col2, col3, col4 = st.columns(4)

        col1.metric("Permissions", summary["total_permissions"])
        col2.metric(
            "Sensitive permissions",
            summary["sensitive_permissions"],
        )
        col3.metric("Tracker indicators", summary["total_trackers"])
        col4.metric(
            "Recognized trackers",
            summary["recognized_trackers"],
        )

        st.divider()

        st.subheader("Permission Findings")
        st.dataframe(
            findings["permissions"],
            width="stretch",
            hide_index=True,
        )

        st.subheader("Third-Party SDK Indicators")
        st.dataframe(
            findings["trackers"],
            width="stretch",
            hide_index=True,
        )

        st.divider()
        st.subheader("Privacy Interpretation")

        st.warning(
            "These findings show requested permissions and "
            "reported SDK indicators. They do not establish "
            "actual data collection or transmission."
        )

        
        if st.button("Generate Meta AI Explanation"):
            with st.spinner("Analyzing findings with Muse Spark..."):
                try:
                    explanation = explain_findings(findings)
                    st.session_state["ai_explanation"] = explanation
                    st.session_state["ai_report"] = findings
                except Exception as error:
                    st.error(f"Meta AI unavailable: {error}")

        if (
            "ai_explanation" in st.session_state
            and st.session_state.get("ai_report") == findings
        ):
            st.success("Explanation generated by Meta Muse Spark")
            st.markdown(st.session_state["ai_explanation"])


        st.download_button(
            "Download Analysis (JSON)",
            data=json.dumps(findings, indent=2),
            file_name="health_app_privacy_report.json",
            mime="application/json",
        )

    except json.JSONDecodeError:
        st.error("Invalid JSON. Please upload a valid JSON report.")
    except Exception as error:
        st.error(f"Unable to analyze the report: {error}")

else:
    st.write("Upload a JSON report to begin analysis.")
